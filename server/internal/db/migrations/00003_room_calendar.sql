CREATE TABLE room_schedule_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    effective_from DATE NOT NULL,
    effective_until DATE,
    published_by_user_id BIGINT NOT NULL REFERENCES users(id),
    reason TEXT NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SUPERSEDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (effective_until IS NULL OR effective_until > effective_from),
    EXCLUDE USING gist (room_id WITH =, daterange(effective_from,effective_until,'[)') WITH &&) WHERE (status='ACTIVE')
);
CREATE TABLE room_weekly_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL REFERENCES room_schedule_versions(id) ON DELETE CASCADE,
    weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    start_minute INTEGER NOT NULL,
    end_minute INTEGER NOT NULL,
    CHECK (start_minute >= 0 AND end_minute <= 1440 AND start_minute < end_minute AND start_minute % 60 = 0 AND end_minute % 60 = 0),
    EXCLUDE USING gist (version_id WITH =, weekday WITH =, int4range(start_minute,end_minute,'[)') WITH &&)
);
CREATE TABLE room_calendar_exceptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    exception_date DATE NOT NULL,
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('CLOSED','REPLACE')),
    closure_type VARCHAR(20) NOT NULL CHECK (closure_type IN ('HOLIDAY','MAINTENANCE','OTHER')),
    reason TEXT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','WITHDRAWN')),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    updated_by_user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
