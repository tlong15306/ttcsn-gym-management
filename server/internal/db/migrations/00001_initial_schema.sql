CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE CHECK (code IN ('MEMBER','PT','RECEPTIONIST','MANAGER','ADMIN')),
    name VARCHAR(80) NOT NULL,
    description TEXT
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(20),
    full_name VARCHAR(150) NOT NULL,
    avatar_path VARCHAR(500),
    role_id SMALLINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','LOCKED')),
    auth_version INTEGER NOT NULL DEFAULT 1 CHECK (auth_version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_users_username_ci ON users (LOWER(username));
CREATE UNIQUE INDEX uq_users_email_ci ON users (LOWER(email));

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    member_code VARCHAR(30) NOT NULL UNIQUE,
    date_of_birth DATE,
    gender VARCHAR(20),
    address TEXT,
    join_date DATE NOT NULL,
    membership_expiry DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (membership_expiry >= join_date)
);
CREATE INDEX idx_members_expiry_status ON members (membership_expiry, status);

CREATE TABLE personal_trainers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    specialty VARCHAR(200),
    experience_text TEXT,
    certificate_path VARCHAR(500),
    approval_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (approval_status IN ('DRAFT','PENDING','APPROVED','REJECTED','SUSPENDED')),
    decision_reason TEXT,
    decided_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    decided_at TIMESTAMPTZ,
    rating_average NUMERIC(3,2) CHECK (rating_average IS NULL OR rating_average BETWEEN 1.00 AND 5.00),
    attendance_rate NUMERIC(5,2) CHECK (attendance_rate IS NULL OR attendance_rate BETWEEN 0.00 AND 100.00),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((approval_status IN ('DRAFT','PENDING') AND decided_at IS NULL) OR (approval_status IN ('APPROVED','REJECTED','SUSPENDED') AND decided_at IS NOT NULL AND decided_by_user_id IS NOT NULL))
);

CREATE TABLE pt_working_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pt_id BIGINT NOT NULL REFERENCES personal_trainers(id) ON DELETE RESTRICT,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (start_time < end_time),
    UNIQUE (pt_id, day_of_week, start_time, end_time)
);

CREATE TABLE pt_unavailability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pt_id BIGINT NOT NULL REFERENCES personal_trainers(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (starts_at < ends_at),
    EXCLUDE USING gist (pt_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&)
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    room_type VARCHAR(50) NOT NULL,
    default_capacity INTEGER NOT NULL CHECK (default_capacity > 0),
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','MAINTENANCE','INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_rooms_name_ci ON rooms (LOWER(name));

CREATE TABLE time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (start_time < end_time),
    EXCLUDE USING gist (int4range(EXTRACT(EPOCH FROM start_time)::INTEGER, EXTRACT(EPOCH FROM end_time)::INTEGER, '[)') WITH &&) WHERE (is_active)
);
CREATE UNIQUE INDEX uq_time_slots_name_active_ci ON time_slots (LOWER(name)) WHERE is_active;

CREATE TABLE room_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    time_slot_id BIGINT NOT NULL REFERENCES time_slots(id) ON DELETE RESTRICT,
    session_date DATE NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED','MAINTENANCE')),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    change_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (starts_at < ends_at),
    UNIQUE (room_id, session_date, time_slot_id),
    UNIQUE (id, session_date, time_slot_id)
);
CREATE INDEX idx_room_sessions_calendar ON room_sessions (session_date, room_id, status);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    room_session_id BIGINT NOT NULL,
    session_date DATE NOT NULL,
    time_slot_id BIGINT NOT NULL,
    pt_id BIGINT REFERENCES personal_trainers(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_PT','CONFIRMED','REJECTED','EXPIRED','CANCELLED','COMPLETED','NO_SHOW')),
    respond_by TIMESTAMPTZ,
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    cancelled_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    cancellation_reason TEXT,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_booking_room_session FOREIGN KEY (room_session_id, session_date, time_slot_id) REFERENCES room_sessions(id, session_date, time_slot_id) ON DELETE RESTRICT,
    CHECK ((status = 'PENDING_PT' AND pt_id IS NOT NULL AND respond_by IS NOT NULL) OR (status <> 'PENDING_PT')),
    CHECK ((status = 'CANCELLED' AND cancelled_at IS NOT NULL AND cancelled_by_user_id IS NOT NULL AND cancellation_reason IS NOT NULL) OR (status <> 'CANCELLED'))
);
CREATE INDEX idx_bookings_session_status ON bookings (room_session_id, status);
CREATE INDEX idx_bookings_member_history ON bookings (member_id, session_date DESC);
CREATE INDEX idx_bookings_pt_history ON bookings (pt_id, session_date DESC) WHERE pt_id IS NOT NULL;
CREATE UNIQUE INDEX uq_booking_member_holds_slot ON bookings (member_id, session_date, time_slot_id) WHERE status IN ('PENDING_PT','CONFIRMED');
CREATE UNIQUE INDEX uq_booking_pt_holds_slot ON bookings (pt_id, session_date, time_slot_id) WHERE pt_id IS NOT NULL AND status IN ('PENDING_PT','CONFIRMED');

CREATE TABLE booking_attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
    participant_type VARCHAR(10) NOT NULL CHECK (participant_type IN ('MEMBER','PT')),
    participant_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    checked_in_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    override_reason TEXT,
    UNIQUE (booking_id, participant_type)
);

CREATE TABLE pt_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE RESTRICT,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    request_scope VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    response_status INTEGER,
    response_body JSONB,
    committed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (actor_user_id, request_scope, idempotency_key)
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(80),
    reason TEXT,
    before_data JSONB,
    after_data JSONB,
    request_id VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_entity ON audit_events (entity_type, entity_id, created_at DESC);
CREATE INDEX idx_audit_actor ON audit_events (actor_user_id, created_at DESC);

